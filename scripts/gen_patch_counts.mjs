import fs from "node:fs";
import path from "node:path";

const csvPath =
  process.env.PATCH_COUNTS_CSV ||
  "D:\\lizard conic\\CoNIC_Patches_256_NoOverlap_Official\\counts.csv";

if (!fs.existsSync(csvPath)) {
  console.error("counts.csv not found:", csvPath);
  process.exit(1);
}

const lines = fs.readFileSync(csvPath, "utf8").trim().split(/\r?\n/);
const classes = lines[0].split(",").map((s) => s.trim());

// counts[i] = [c0, c1, ...] for patch index i (conic_%06d)
const counts = [];
for (let i = 1; i < lines.length; i++) {
  const parts = lines[i].split(",");
  counts.push(classes.map((_, c) => Number(parts[c]) || 0));
}

const outPath = path.join(process.cwd(), "src", "lib", "patchCounts.ts");
const body = `// AUTO-GENERATED by scripts/gen_patch_counts.mjs
// 每張 patch（conic_%06d）各類細胞核數量，索引 = 檔名數字。
export const patchCountClasses = ${JSON.stringify(classes)} as const;
export const patchCounts: number[][] = ${JSON.stringify(counts)};

export function patchCountsFor(index: number): { key: string; count: number }[] {
  const row = patchCounts[index];
  if (!row) return [];
  return patchCountClasses.map((key, i) => ({ key, count: row[i] ?? 0 }));
}
`;
fs.writeFileSync(outPath, body);
console.log("Wrote", outPath, "patches:", counts.length, "classes:", classes.join(","));
