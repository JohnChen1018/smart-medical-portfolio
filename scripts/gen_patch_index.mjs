import fs from "node:fs";
import path from "node:path";

const csvPath =
  process.env.PATCH_COUNTS_CSV ||
  "D:\\lizard conic\\CoNIC_Patches_256_NoOverlap_Official\\counts.csv";

if (!fs.existsSync(csvPath)) {
  console.error("counts.csv not found:", csvPath);
  process.exit(1);
}

const csv = fs.readFileSync(csvPath, "utf8").trim().split(/\r?\n/);
const classes = csv[0].split(",");
const byClass = { all: [] };
for (const c of classes) byClass[c] = [];

for (let i = 1; i < csv.length; i++) {
  const parts = csv[i].split(",");
  const idx = i - 1;
  byClass.all.push(idx);
  for (let c = 0; c < classes.length; c++) {
    const v = Number(parts[c]) || 0;
    if (v > 0) byClass[classes[c]].push(idx);
  }
}

const outPath = path.join(process.cwd(), "src", "lib", "patchClassIndex.ts");
const body = `// AUTO-GENERATED by scripts/gen_patch_index.mjs
export const patchClassKeys = ${JSON.stringify(classes)} as const;
export type PatchClassKey = (typeof patchClassKeys)[number] | "all";
export const patchIndicesByClass: Record<string, number[]> = ${JSON.stringify(byClass)};
`;
fs.writeFileSync(outPath, body);
console.log(
  "Wrote",
  outPath,
  Object.fromEntries(Object.entries(byClass).map(([k, v]) => [k, v.length])),
);
